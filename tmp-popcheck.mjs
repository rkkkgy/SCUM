import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const { fetchServerPopulation } = await import('./lib/sources.mjs');
const pop = await fetchServerPopulation();
console.log('population', JSON.stringify(pop));
const { Monitor } = await import('./lib/monitor.mjs');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'scum-pop-'));
const m = new Monitor({ dataDir: dir, intervalSec: 61, pruneData: false });
await m.poll();
const s = m.status();
console.log('status.server', JSON.stringify(s.server));
console.log('counts', JSON.stringify(s.counts));
fs.rmSync(dir, { recursive: true, force: true });
